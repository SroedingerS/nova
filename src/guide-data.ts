guideArticles.sort(
  (a, b) =>
    guideCategories.findIndex((c) => c.id === a.category) -
    guideCategories.findIndex((c) => c.id === b.category),
);

export const normalizeGuideQuery = (value: string) =>
  value
    .toLocaleLowerCase("ru")
    .replaceAll("ё", "е")
    .replace(/[^\p{L}\p{N}]+/gu, " ")
    .trim();
export function matchesGuide(article: GuideArticle, query: string, extra = "") {
  const words = normalizeGuideQuery(query).split(" ").filter(Boolean);
  const haystack = normalizeGuideQuery(
    [
      article.title,
      article.intro,
      ...article.steps,
      article.note,
      article.keywords,
      extra,
    ].join(" "),
  );
  return words.every((word) => haystack.includes(word));
}
